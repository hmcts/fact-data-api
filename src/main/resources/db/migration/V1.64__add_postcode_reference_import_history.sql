CREATE TABLE postcode_reference_import (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_version VARCHAR(150) NOT NULL UNIQUE,
    onspd_release CHAR(7) NOT NULL,
    blob_etag VARCHAR(100) NOT NULL,
    record_count BIGINT NOT NULL,
    imported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT postcode_reference_import_record_count_check
        CHECK (record_count > 0)
);
